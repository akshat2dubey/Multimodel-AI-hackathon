#!/bin/bash
set -euo pipefail
cd "F:/Akshat\edc ideas\LadderLens\MultiModel\hackathon-trackb"

log() { printf '%s\n' "$*" >&2; }

# ----------------------------------------------------------------------
# Exact rename map: contextual, applied in listed order. More specific
# phrases first; the generic catch-all last.
# ----------------------------------------------------------------------
declare -a MAP=()
add_map() { MAP+=("$1"); }

add_map 'FloodMapper — Pipeline Orchestrator'   'Jalnetra — Pipeline Orchestrator'
add_map 'FloodMapper — Full Pipeline'           'Jalnetra — Full Pipeline'
add_map 'FloodMapper — Complete Tutorial'       'Jalnetra — Complete Tutorial'
add_map 'FloodMapper — Status Report to CEO'    'Jalnetra — Status Report to CEO'
add_map 'FloodMapper — Demo Mode'               'Jalnetra — Demo Mode'
add_map 'FloodMapper — Track B Dashboard'       'Jalnetra — Track B Dashboard'
add_map 'FloodMapper: Mapping Flood Damage'     'Jalnetra: Mapping Flood Damage'
add_map 'Situation Report — FloodMapper'        'Situation Report — Jalnetra'
add_map 'FloodMapper Dashboard — Flask'         'Jalnetra Dashboard — Flask'
add_map 'FloodMapper Dashboard — Open'          'Jalnetra Dashboard — Open'
add_map 'FloodMapper System'                    'Jalnetra System'
add_map 'FloodMapper Team'                      'Jalnetra Team'
add_map 'FloodMapper Pipeline'                  'Jalnetra Pipeline'
add_map 'FloodMapper dashboard'                 'Jalnetra dashboard'
add_map 'FloodMapper damage_assessment.py'      'Jalnetra damage_assessment.py'
add_map 'FloodMapper demonstrates'              'Jalnetra demonstrates'
add_map 'FloodMapper is an end-to-end'          'Jalnetra is an end-to-end'
add_map 'FloodMapper exists to'                  'Jalnetra exists to'
add_map 'Our Solution: FloodMapper'              'Our Solution: Jalnetra'
add_map 'Generated by FloodMapper'              'Generated by Jalnetra'
add_map 'By FloodMapper System'                 'By Jalnetra System'
add_map 'FloodMapper'                           'Jalnetra'

# ----------------------------------------------------------------------
# Report scope before touching anything.
# ----------------------------------------------------------------------
log "========================================================="
log "Jalnetra rename — exact scope and replacements"
log "========================================================="
log ""
log "Files that will be touched (tracked project files only):"
TOUCH=()
for f in \
  dashboard/app.py \
  dashboard/templates/demo.html \
  dashboard/templates/index.html \
  dashboard/templates/report_wrapper.html \
  docs/CEO_STATUS_REPORT.md \
  docs/PROJECT_TUTORIAL.md \
  report/report.md \
  report/situation_report.html \
  requirements.txt \
  scripts/damage_assessment.py \
  scripts/generate_report.py \
  scripts/run_pipeline.py \
  scripts/fetch_osm.py \
  scripts/inference.py \
  scripts/train_segmentation.py \
  ; do
  if [ -f "$f" ]; then
    log "  $f"
    TOUCH+=("$f")
  else
    log "  (missing, skip) $f"
  fi
done
log ""
log "Textual replacements (each applied in the order listed above):"
sep="  "
for entry in "${MAP[@]}"; do
  old="${entry%% *}"
  new="${entry#* }"
  [ "$old" = "$new" ] && continue
  log "${sep}'${old}'  ->  '${new}'"
  sep="      "
done
log ""
log "NOTE: README.md is intentionally NOT in the touch list."
log "      (That is the file you just rewrote and staged for the rebase.)"
log ""

# ----------------------------------------------------------------------
# Pre-flight counts.
# ----------------------------------------------------------------------
pending=0
for f in "${TOUCH[@]}"; do
  before=$(grep -c 'FloodMapper' "$f" || true)
  if [ "$before" -gt 0 ]; then
    pending=$((pending + 1))
  fi
done
log "Files pending rename (contain FloodMapper before this script): $pending"
log ""

# ----------------------------------------------------------------------
# Apply replacements, per file.
# ----------------------------------------------------------------------
for f in "${TOUCH[@]}"; do
  before=$(grep -c 'FloodMapper' "$f" || true)
  if [ "$before" -eq 0 ]; then
    log "clean (no FloodMapper): $f"
    continue
  fi

  log "renaming: $f  (before FloodMapper count: $before)"

  content=$(cat "$f" || true)
  for entry in "${MAP[@]}"; do
    old="${entry%% *}"
    new="${entry#* }"
    [ "$old" = "$new" ] && continue
    content="${content//$old/$new}"
  done

  # Preserve trailing-newline style of the original file.
  last_char=$(printf '%s' "$content" | tail -c 1)
  printf '%s' "$content" > "$f"
  if [ -n "$last_char" ] && [ "$last_char" != $'\n' ]; then
    printf '\n' >> "$f"
  fi

  after=$(grep -c 'FloodMapper' "$f" || true)
  jal=$(grep -c 'Jalnetra' "$f" || true)
  log "  after FloodMapper count: $after   Jalnetra count: $jal"
done
log ""

# ----------------------------------------------------------------------
# Post-flight: touched files must contain no FloodMapper.
# ----------------------------------------------------------------------
log "========================================================="
log "POST-FLIGHT CHECK"
log "========================================================="
log ""
bad=0
for f in "${TOUCH[@]}"; do
  c=$(grep -c 'FloodMapper' "$f" || true)
  j=$(grep -c 'Jalnetra' "$f" || true)
  if [ "$c" -gt 0 ]; then
    log "FAIL — still contains FloodMapper: $f ($c occurrences)"
    bad=$((bad + 1))
  fi
  log "  $f : FloodMapper=$c  Jalnetra=$j"
done
log ""
log "Files touched: ${#TOUCH[@]}"
log "Files still containing FloodMapper after rename: $bad"
log ""
log "Repo-wide (tracked files, excluding .git / __pycache__):"
tot_fm=$(grep -rIc 'FloodMapper' --exclude-dir=.git --exclude-dir=__pycache__ . || true)
tot_ja=$(grep -rIc 'Jalnetra' --exclude-dir=.git --exclude-dir=__pycache__ . || true)
log "  FloodMapper occurrences total : $tot_fm"
log "  Jalnetra occurrences total    : $tot_ja"
log ""
if [ "$bad" -eq 0 ]; then
  log "RESULT: rename complete — no FloodMapper remains in the touched files."
else
  log "RESULT: rename incomplete — $bad file(s) still contain FloodMapper."
  exit 1
fi
